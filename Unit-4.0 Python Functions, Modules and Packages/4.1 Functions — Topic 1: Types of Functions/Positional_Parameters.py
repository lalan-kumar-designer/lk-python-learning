# Positional Parameters

def student(name, age):
    print("Name:", name)
    print("Age:", age)

student("Lalan", 17)


def subtract(a, b):
    print("Difference:", a - b)

subtract(20, 5)
subtract(5, 20)


def student_details(name, roll, branch):
    print("Name:", name)
    print("Roll No:", roll)
    print("Branch:", branch)

student_details("Lalan Kumar", 22, "Electrical Engineering")