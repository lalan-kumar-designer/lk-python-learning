# Returning Value

def add(a, b):
    return a + b

result = add(10, 20)
print("Sum:", result)


def square(number):
    return number * number

print("Square:", square(5))


def multiply(a, b):
    return a * b

result = multiply(4, 5)
print("Product:", result)


def calculate_area(length, width):
    return length * width

area = calculate_area(5, 4)
print("Area:", area)