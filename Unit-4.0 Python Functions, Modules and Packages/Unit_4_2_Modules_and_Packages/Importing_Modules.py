# Importing Modules

# Import the math module for mathematical operations.
import math

print(math.sqrt(25))
print(math.factorial(5))

# Import the random module to generate random values.
import random

print(random.randint(1, 10))

# Import the datetime module to work with dates and times.
import datetime

print(datetime.date.today())

# Import specific functions and constants from math.
from math import pi, pow

print(pi)
print(pow(2, 3))

# Use an alias to access the math module.
import math as m

print(m.sqrt(64))